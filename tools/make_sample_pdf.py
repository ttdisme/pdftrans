def build_doc(title: str, subtitle: str, sections: list[tuple[str, str]], pages: int = 2):
    doc = fitz.open()
    margin = 72.0
    first = True

    for page_no in range(pages):
        page = doc.new_page(width=595, height=842)
        box = fitz.Rect(margin, margin, 595 - margin, 842 - margin)
        parts: list[str] = []

        if first:
            parts.append(f"<h1>{title}</h1>")
            parts.append(f"<p><i>{subtitle}</i></p>")
            first = False
        else:
            parts.append(f"<h2>{title} (continued)</h2>")

        for heading, body in sections:
            parts.append(f"<h2>{heading}</h2>")
            parts.append(f"<p>{body}</p>")

        if page_no == pages - 1:
            parts.append("<p><i>Sample document generated by tools/make_sample_pdf.py</i></p>")

        page.insert_htmlbox(
            box,
            "".join(parts),
            css="* {font-family: sans-serif; font-size: 10.5px; line-height: 1.5; font-variant-ligatures: none;}"
            "h1 {font-size: 17px;} h2 {font-size: 12px;}",
        )

    return doc


def main() -> int:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("examples/sample-paper.pdf")
    title = sys.argv[2] if len(sys.argv) > 2 else "Sample Manuscript: Reactor Performance"
    out.parent.mkdir(parents=True, exist_ok=True)

    doc = build_doc(
        title,
        "Placeholder text for the PDF reader demo - not a real publication",
        BODY if "sample-paper" in out.name else ABSTRACT_ONLY,
        pages=2,
    )
    doc.save(str(out), garbage=4, deflate=True)
    doc.close()
    print(f"written: {out} ({out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
